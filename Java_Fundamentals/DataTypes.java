package Basicjavaandsomearrayconcept;
public class DataTypes 
{
    public static void main(String[] args)
    {
        //Integer Data Types
        byte b = 5;
        short year = 2026;
        int salary = 100000;
        long population = 12000000000000L;

        //floating point Data Types
        float percentage = 89.75f;
        double pi = 3.142587;

        //character data type
        char grade='A';

        //boolean
        boolean ispassed = true;

        System.out.println("Primitive Data Types");

        System.out.println("Byte value :" +b);
        System.out.println("Short value :" +year);
        System.out.println("Int Value :" +salary);
        System.out.println("Long :" +population);
        System.out.println("float :" +percentage);
        System.out.println("Double :" +pi);

        System.out.println("Char Value :" +grade);

        System.out.println("Boolean Value: " +ispassed);



    }

    
}
