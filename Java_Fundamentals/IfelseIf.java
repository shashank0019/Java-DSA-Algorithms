package Basicjavaandsomearrayconcept;
public class IfelseIf 
{
    public static void main(String[] args)
    {
        int marks = 95;

        if(marks>=90)
        {
            System.out.println("officer");
        }
        else if(marks>=80)
        {
            System.out.println("clerk");
        }
        else if(marks>=70)
        {
            System.out.println("jawan");
        }
        else
        {
            System.out.println("office boy");
        }
    }
    
}
